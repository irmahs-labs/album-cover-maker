// Writes src/font-faces.css: the @font-face rules for every family in PAIRS
// (src/lib/fonts.ts), served from the Fontsource npm packages instead of
// Google. Run `npm run fonts` after changing PAIRS, once any new family is
// installed with `npm install @fontsource/<family-name>`.
//
// It keeps the Latin and Latin Extended subsets (enough for French and the
// other European languages), regular, bold and both italics where a family
// has them, and woff2 only, which every current browser reads.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const STYLES = ["400", "400-italic", "700", "700-italic"];
const SUBSET =
  /^\/\* [a-z0-9-]+-(latin|latin-ext)-\d{3}-(normal|italic) \*\/$/u;

const source = readFileSync("src/lib/fonts.ts", "utf8");
const pairs = source.slice(
  source.indexOf("PAIRS = ["),
  source.indexOf("] as const")
);
const families = [
  ...new Set([...pairs.matchAll(/"([^"]+)"/gu)].map((m) => m[1])),
];

const rules = [];
const missing = [];
for (const family of families) {
  const pkg = `@fontsource/${family.toLowerCase().replaceAll(" ", "-")}`;
  if (!existsSync(`node_modules/${pkg}`)) {
    missing.push(pkg);
    continue;
  }
  for (const style of STYLES) {
    const file = `node_modules/${pkg}/${style}.css`;
    if (!existsSync(file)) {
      continue;
    }
    // Each block is a comment naming the subset, then its @font-face rule.
    for (const block of readFileSync(file, "utf8").split(/\n(?=\/\* )/u)) {
      const [comment, ...rest] = block.trim().split("\n");
      if (!SUBSET.test(comment)) {
        continue;
      }
      const woff2 = rest
        .join("\n")
        .match(/url\(\.\/files\/([^)]+\.woff2)\)/u)?.[1];
      if (!woff2) {
        throw new Error(`No woff2 in ${file}: ${comment}`);
      }
      rules.push(
        rest
          .join("\n")
          .replace(
            /src: [^;]+;/u,
            `src: url(../node_modules/${pkg}/files/${woff2}) format("woff2");`
          )
      );
    }
  }
}

if (missing.length) {
  console.error(
    `Not installed: ${missing.join(" ")}\nRun: npm install ${missing.join(" ")}`
  );
  process.exit(1);
}

writeFileSync(
  "src/font-faces.css",
  `/* Generated by scripts/font-faces.mjs from PAIRS in src/lib/fonts.ts. Do not edit; run \`npm run fonts\`. */\n${rules.join("\n")}\n`
);
console.log(
  `src/font-faces.css: ${families.length} families, ${rules.length} font faces`
);
